import { test, expect, type Page } from '@playwright/test'
import { Chess } from 'chess.js'
import { readFileSync } from 'node:fs'

const puzzles=JSON.parse(readFileSync('src/data/puzzles.json','utf8')) as {id:string;moves:string[];themes:string[]}[]
const selectSquare=(page:Page,square:string)=>page.getByRole('button',{name:new RegExp('^'+square+'(?: |$)')})
async function move(page:Page,from:string,to:string) {
  await selectSquare(page,from).click()
  await selectSquare(page,to).click()
}

test('dashboard opens the featured variation and replay changes the displayed move',async({page})=>{
  await page.clock.install()
  await page.goto('/')
  await expect(page.getByRole('heading',{name:'Welcome to the Academy'})).toBeVisible()
  await page.getByRole('link',{name:/Ruy Lopez Closed Variation/}).click()
  await expect(page.getByRole('heading',{name:'Ruy Lopez',exact:true})).toBeVisible()
  await page.getByLabel('Playback speed').selectOption({label:'Slow'})
  const playButton=page.getByRole('button',{name:'Play',exact:true})
  await playButton.click()
  await page.clock.fastForward(1650)
  await expect(page.getByRole('heading',{name:'e4',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Pause',exact:true}).click()
  await page.clock.fastForward(4000)
  await expect(page.getByRole('heading',{name:'e4',exact:true})).toBeVisible()
  await playButton.click()
  await page.clock.fastForward(1650)
  await expect(page.getByRole('heading',{name:'e5',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Next move'}).click()
  await expect(page.getByRole('heading',{name:'Nf3',exact:true})).toBeVisible()
  await expect(playButton).toBeVisible()
  await page.getByRole('link',{name:'Berlin Defense'}).click()
  await expect(page.getByRole('button',{name:'First move'})).toBeDisabled()
  await page.getByRole('button',{name:'Last move'}).click()
  await expect(page.getByText(/(20|2[1-9]|30) \/ (20|2[1-9]|30) half-moves/)).toBeVisible()
  await expect.poll(()=>page.locator('[aria-label="Move list"]').evaluate(list=>list.scrollTop)).toBeGreaterThan(0)
})
test('tap moves solve a puzzle and progress survives reload on mobile',async({page})=>{
  await page.setViewportSize({width:390,height:844})
  const sample=puzzles.find(p=>p.themes.includes('mateIn1'))!
  await page.goto('/puzzles/'+sample.id)
  const first=sample.moves[0]
  await selectSquare(page,first.slice(0,2)).tap()
  await selectSquare(page,first.slice(2,4)).tap()
  if(first[4])await page.getByRole('button',{name:first[4]==='q'?'Promote to queen':first[4]==='r'?'Promote to rook':first[4]==='b'?'Promote to bishop':'Promote to knight'}).tap()
  await expect(page.getByRole('heading',{name:'Puzzle solved'})).toBeVisible()
  await page.reload()
  await expect(page.getByText('Solved',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Open navigation'}).click()
  await page.getByRole('link',{name:'My Progress',exact:true}).click()
  await expect(page.getByRole('heading',{name:'My Progress'})).toBeVisible()
  expect(await page.locator('body').evaluate(body=>body.scrollWidth)).toBeLessThanOrEqual(390)
})
