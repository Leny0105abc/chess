test('a guest can complete a lesson, answer interactive quiz items, and earn a badge',async({page})=>{
  await page.goto('/')
  await page.getByRole('link',{name:'Continue Learning'}).click()
  await page.getByRole('button',{name:'Start guided practice'}).click()
  await move(page,'e2','e4')
  await page.getByRole('button',{name:'Take lesson quiz'}).click()
  for(let i=0;i<5;i++){
    await expect(page.getByText('Question '+(i+1)+' of 5',{exact:true})).toBeVisible()
    const title=await page.locator('.quiz-panel h2').innerText()
    if(title.startsWith('Select e4'))await selectSquare(page,'e4').click()
    else if(title.startsWith('Play the recorded'))await move(page,'e2','e4')
    else if(title.startsWith('Which piece'))await page.getByRole('button',{name:'pawn',exact:true}).click()
    else if(title.startsWith('True or false'))await page.getByRole('button',{name:'False',exact:true}).click()
    else await page.getByRole('button',{name:'Checkmate',exact:true}).click()
  }
  await expect(page.getByRole('heading',{name:'Score 100%'})).toBeVisible()
  await page.getByRole('button',{name:'Complete lesson'}).click()
  await page.goto('/progress')
  await expect(page.locator('.badge-card.earned').getByRole('heading',{name:'First Lesson'})).toBeVisible()
})
test('opening trainer responds as Black and saves mastery in examination mode',async({page})=>{
  await page.goto('/openings/ruy-lopez/closed-variation?practice=1')
  await page.getByLabel('Training mode').selectOption('Examination')
  await page.getByRole('button',{name:'Start practice'}).click()
  const game=new Chess()
  const san='e4 e5 Nf3 Nc6 Bb5 a6 Ba4 Nf6 O-O Be7 Re1 b5 Bb3 d6 c3 O-O h3 Nb8 d4 Nbd7'.split(' ')
  for(let i=0;i<san.length;i+=2){
    const played=game.move(san[i])
    await expect(selectSquare(page,played.from)).toBeVisible()
    await move(page,played.from,played.to)
    game.move(san[i+1])
  }
  await expect(page.getByRole('heading',{name:'Variation complete'})).toBeVisible()
  await expect(page.getByText(/Last mastery 100%/)).toBeVisible()
})
test('installed service worker serves an unopened lesson offline',async({page,context})=>{
  await page.goto('/')
  await page.evaluate(async()=>{await navigator.serviceWorker.ready})
  await expect.poll(()=>page.evaluate(()=>Boolean(navigator.serviceWorker.controller))).toBe(true)
  await context.setOffline(true)
  await page.goto('/learn/introduction-to-chess')
  await expect(page.getByRole('heading',{name:'Introduction to chess'})).toBeVisible()
})

test('game analysis imports PGN, evaluates a position and restores saved annotations',async({page})=>{
  await page.clock.install()
  await page.goto('/analysis')
  const playButton=page.getByRole('button',{name:'Play',exact:true})
  await expect(playButton).toBeDisabled()
  await page.getByLabel('Paste PGN or FEN').fill('1. e4 e5 2. Nf3 Nc6')
  await page.getByRole('button',{name:'Load PGN',exact:true}).click()
  await page.getByLabel('Playback speed').selectOption({label:'Slow'})
  await playButton.click()
  const current=page.locator('.move-grid [aria-current="step"]')
  for(const san of ['e4','e5','Nf3','Nc6']){
    await page.clock.fastForward(1650)
    await expect(current).toContainText(san)
  }
  await expect(playButton).toBeVisible()
  await page.getByLabel('Position annotation').fill('Compare the Spanish and Italian setups.')
  await page.getByRole('button',{name:'Save analysis',exact:true}).click()
  await expect(page.getByText('Analysis saved on this device.')).toBeVisible()
  await playButton.click()
  await expect(page.getByRole('button',{name:'First move',exact:true})).toBeDisabled()
  await page.getByRole('button',{name:'Evaluate Position',exact:true}).click()
  await expect(playButton).toBeVisible()
  await page.clock.fastForward(1650)
  await expect(page.getByRole('button',{name:'First move',exact:true})).toBeDisabled()
  await expect(page.getByText(/Depth 10 · Best move/)).toBeVisible({timeout:25_000})
  await page.reload()
  await page.getByRole('button',{name:'Load saved analysis',exact:true}).click()
  await page.getByRole('button',{name:'Last move',exact:true}).click()
  await expect(page.getByLabel('Position annotation')).toHaveValue('Compare the Spanish and Italian setups.')
})
